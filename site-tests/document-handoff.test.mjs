test('every library creation path has a booking-supported document type',()=>{
 const paths=new Set();
 for(const library of ['documents/library.html','documents/library-ht.html']){
  const html=read(library);
  for(const match of html.matchAll(/href=["']([^"']*(?:create(?:-ht)?\.html\?type=|\/create\/)[^"']*)["']/g)){
   const url=new URL(match[1].replaceAll('&amp;','&'),'https://safenotarize.com/'+library);
   paths.add(url.pathname+url.search);
   const type=url.searchParams.get('type')||url.pathname.split('/').pop().replace('.html','');
   for(const book of booking){
    const source=read(book),values=source.match(/DOCUMENT_TYPE_ALLOWLIST = new Set\((\[[^;]+\])\)/)?.[1];
    assert.ok(values,book+' allowlist expected');
    assert.ok(JSON.parse(values).includes(type),type+' must be accepted by '+book);
   }
  }
 }
 assert.equal(paths.size,50,'All English and Creole document choices must be covered');
});

