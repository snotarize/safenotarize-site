test('installed-app requests cannot reuse an old cached handoff client',async()=>{
 const {runInNewContext}=await import('node:vm');
 const listeners=new Map(),calls=[];
 runInNewContext(read('sw.js'),{self:{location:{origin:'https://safenotarize.com'},addEventListener:(type,fn)=>listeners.set(type,fn)},
  URL,Response,fetch:async(request,options)=>{calls.push(options?.cache);return new Response('fresh handoff')},
  caches:{match:async()=>{throw Error('Cached workflow asset must not be read')}}});
 for(const asset of ['document-handoff.js','document-handoff-config.js']){
  let response;
  listeners.get('fetch')({request:{method:'GET',url:'https://safenotarize.com/assets/'+asset+'?v=current'},respondWith:p=>response=p});
  assert.equal(await (await response).text(),'fresh handoff');
 }
 assert.deepEqual(calls,['no-store','no-store']);
});


