function inlineScripts(html){
 return [...html.matchAll(/<script\b([^>]*)>([\s\S]*?)<\/script>/gi)]
  .filter(x=>!/(?:\bsrc=|application\/ld\+json|application\/json)/i.test(x[1])&&x[2].trim()).map(x=>x[2]);
}
